/*
 * Builds a portable, multi-file export.
 *
 * The old export put every media file into one enormous HTML document.  This
 * export keeps the HTML and game code in portable.html, then stores the media
 * as ordered JavaScript asset parts in portable-parts/.  Each part is kept
 * below the GitHub-friendly limit and registers its data with the shared
 * window.__portableAssetChunks registry.  portable.html assembles that
 * registry into data URLs when the game asks for an asset.
 */

const fs = require('fs');
const path = require('path');

const root = __dirname;
const outputPath = path.join(root, 'portable.html');
const partsDirectory = path.join(root, 'portable-parts');

// Leave room below both the requested 25 MB ceiling and the 23 MB target.
const MAX_PART_BYTES = 22_500_000;
// Keeping individual JavaScript strings modest avoids parser limits while
// still allowing several chunks to share a part file.
const BASE64_CHUNK_CHARS = 6_000_000;

const mediaTypes = {
  '.fbx': 'application/octet-stream',
  '.flac': 'audio/flac',
  '.gif': 'image/gif',
  '.glb': 'model/gltf-binary',
  '.jpeg': 'image/jpeg',
  '.jpg': 'image/jpeg',
  '.mp3': 'audio/mpeg',
  '.mp4': 'video/mp4',
  '.ogg': 'audio/ogg',
  '.png': 'image/png',
  '.wav': 'audio/wav'
};

function collectMediaFiles(directory, files = []) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name === '.git' || entry.name === 'portable-parts') {
      continue;
    }

    const absolutePath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      collectMediaFiles(absolutePath, files);
      continue;
    }

    if (mediaTypes[path.extname(entry.name).toLowerCase()]) {
      files.push(absolutePath);
    }
  }
  return files.sort();
}

function assetKey(absolutePath) {
  return path.relative(root, absolutePath).split(path.sep).join('/');
}

function createAssetSnippet(key, mimeType, base64Chunk, isFirstChunk) {
  const keyLiteral = JSON.stringify(key);
  const mimeLiteral = JSON.stringify(mimeType);
  const chunkLiteral = JSON.stringify(base64Chunk);
  const mimeRegistration = isFirstChunk
    ? `window.__portableAssetMimes[${keyLiteral}] = ${mimeLiteral};\n`
    : '';

  return [
    `window.__portableAssetChunks[${keyLiteral}] = window.__portableAssetChunks[${keyLiteral}] || [];`,
    `window.__portableAssetChunks[${keyLiteral}].push(${chunkLiteral});`,
    mimeRegistration
  ].join('\n');
}

function writeAssetParts() {
  fs.mkdirSync(partsDirectory, { recursive: true });
  for (const entry of fs.readdirSync(partsDirectory)) {
    if (/^asset-part-\d+\.js$/.test(entry)) {
      fs.unlinkSync(path.join(partsDirectory, entry));
    }
  }

  const header = [
    '/* Generated by build-portable.js. Keep these files beside portable.html. */',
    'window.__portableAssetChunks = window.__portableAssetChunks || Object.create(null);',
    'window.__portableAssetMimes = window.__portableAssetMimes || Object.create(null);',
    ''
  ].join('\n');
  const footer = '\n';
  const parts = [];
  let current = header;

  const flush = () => {
    if (current === header) return;
    current += footer;
    const partName = `asset-part-${String(parts.length + 1).padStart(3, '0')}.js`;
    fs.writeFileSync(path.join(partsDirectory, partName), current);
    parts.push(partName);
    current = header;
  };

  for (const absolutePath of collectMediaFiles(root)) {
    const key = assetKey(absolutePath);
    const mimeType = mediaTypes[path.extname(key).toLowerCase()];
    const base64 = fs.readFileSync(absolutePath).toString('base64');
    let chunkIndex = 0;

    for (let offset = 0; offset < base64.length; offset += BASE64_CHUNK_CHARS) {
      const base64Chunk = base64.slice(offset, offset + BASE64_CHUNK_CHARS);
      const snippet = createAssetSnippet(key, mimeType, base64Chunk, chunkIndex === 0);
      chunkIndex += 1;

      if (Buffer.byteLength(current) + Buffer.byteLength(snippet) + Buffer.byteLength(footer) > MAX_PART_BYTES) {
        flush();
      }
      current += `${snippet}\n`;
    }
  }
  flush();

  return parts;
}

function inlineAudioSources(html) {
  return html.replace(
    /\b(src)=(")(\/[^"]+)(\2)/g,
    (_match, _attribute, quote, source) =>
      `data-portable-src=${quote}${source}${quote}`
  );
}

function createPortablePage(parts) {
  const sourceHtml = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
  const countdownSource = fs.readFileSync(path.join(root, 'countdown.js'), 'utf8');
  const gameSource = fs.readFileSync(path.join(root, 'game.js'), 'utf8');
  const assetPartTags = parts
    .map((partName) => `  <script src="portable-parts/${partName}"></script>`)
    .join('\n');

  const html = inlineAudioSources(sourceHtml)
    .replace('  <script type="module" src="countdown.js"></script>\n', '')
    .replace('  <script type="module" src="game.js"></script>\n', '');

  const portableRuntime = `
  <!-- PORTABLE EXPORT: asset-part files above share this registry. -->
${assetPartTags}
  <script>
    const PORTABLE_ASSET_CHUNKS = window.__portableAssetChunks || Object.create(null);
    const PORTABLE_ASSET_MIMES = window.__portableAssetMimes || Object.create(null);
    const PORTABLE_ASSET_CACHE = Object.create(null);
    window.__portableAssets = PORTABLE_ASSET_CACHE;

    function portableAssetUrl(value) {
      if (typeof value !== 'string' || value.startsWith('data:') || value.startsWith('blob:')) {
        return value;
      }

      const rawKey = value
        .replace(/^https?:\\/\\/[^/]+/, '')
        .replace(/^\\/+/, '')
        .replace(/^\\.\\//, '')
        .split('?')[0];
      let key = rawKey;
      try {
        key = decodeURIComponent(rawKey);
      } catch {
        // Keep the raw path if a caller passes a malformed escaped URL.
      }
      const chunks = PORTABLE_ASSET_CHUNKS[key];
      if (!chunks) return value;
      if (!PORTABLE_ASSET_CACHE[key]) {
        const mimeType = PORTABLE_ASSET_MIMES[key] || 'application/octet-stream';
        PORTABLE_ASSET_CACHE[key] = \`data:\${mimeType};base64,\${chunks.join('')}\`;
      }
      return PORTABLE_ASSET_CACHE[key];
    }

    // Keep the game's existing absolute media URLs intact while redirecting
    // browser resource loading to the asset parts beside this HTML file.
    for (const [prototype, property] of [
      [window.HTMLImageElement?.prototype, 'src'],
      [window.HTMLMediaElement?.prototype, 'src'],
      [window.HTMLSourceElement?.prototype, 'src']
    ]) {
      if (!prototype) continue;
      const descriptor = Object.getOwnPropertyDescriptor(prototype, property);
      if (!descriptor?.set) continue;
      Object.defineProperty(prototype, property, {
        configurable: descriptor.configurable,
        enumerable: descriptor.enumerable,
        get: descriptor.get,
        set(value) {
          descriptor.set.call(this, portableAssetUrl(value));
        }
      });
    }

    for (const element of document.querySelectorAll('[data-portable-src]')) {
      element.src = portableAssetUrl(element.getAttribute('data-portable-src'));
    }

    if (typeof window.fetch === 'function') {
      const nativeFetch = window.fetch.bind(window);
      window.fetch = (input, init) => {
        if (input instanceof Request) {
          return nativeFetch(new Request(portableAssetUrl(input.url), input), init);
        }
        return nativeFetch(portableAssetUrl(input), init);
      };
    }

    // The online-only Websim hooks are optional in a copied standalone bundle.
    window.websim = window.websim || {};
    window.websim.addEventListener = window.websim.addEventListener || (() => {});
    window.websim.getUser = window.websim.getUser || (async () => null);
    window.websim.getCurrentUser = window.websim.getCurrentUser || (async () => null);
    window.websim.postComment = window.websim.postComment || (async () => ({
      error: 'Online comments are unavailable in the portable export.'
    }));
  </script>
  <script type="module">
${countdownSource}
  </script>
  <script type="module">
${gameSource}
  </script>
`;

  return `${html.replace('</body>', `${portableRuntime}</body>`)}
<!--
  Cartman Royale portable export.
  Keep portable.html and every file in portable-parts/ together.
  The ordered asset parts communicate through window.__portableAssetChunks.
-->
`;
}

const parts = writeAssetParts();
fs.writeFileSync(outputPath, createPortablePage(parts));

const outputFiles = [
  outputPath,
  ...parts.map((partName) => path.join(partsDirectory, partName))
];
const largest = outputFiles
  .map((filePath) => ({ filePath, bytes: fs.statSync(filePath).size }))
  .sort((a, b) => b.bytes - a.bytes)[0];

console.log(`Wrote portable.html and ${parts.length} asset parts.`);
console.log(`Largest output: ${path.relative(root, largest.filePath)} (${largest.bytes} bytes).`);
